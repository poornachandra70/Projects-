numbers = (20, 10)

a = numbers[0]
b = numbers[1]

operator = "+"

if operator == "+":
    print("Result:", a + b)

elif operator == "-":
    print("Result:", a - b)

elif operator == "*":
    print("Result:", a * b)

elif operator == "/":
    print("Result:", a / b)

else:
    print("Invalid operator")